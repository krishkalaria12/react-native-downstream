#!/usr/bin/env node
// Writes src/cpp/downstream/ExportNames.cpp, the fence-language to file
// extension table a code download names its file with.
//
//     node src/cpp/downstream/generate-export-names.mjs
//
// No build runs this: the output is checked in, and `pnpm test:native` covers
// the names it produces. The map is Streamdown's `languageExtensionMap`,
// vendored from `lib/code-block/download-button.tsx` into
// `export-extensions.json` next to this script, with its Apache-2.0 notice.
// That is why the table is generated rather than hand-written: the notice has
// to travel with the data, and the file it came from is the only authority for
// the data.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const source = resolve(join(HERE, 'export-extensions.json'));
const out = resolve(join(HERE, 'ExportNames.cpp'));

const arg = (name, fallback) => {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 && process.argv[index + 1]
    ? process.argv[index + 1]
    : fallback;
};

const {
  map,
  source: origin,
  commit,
  license,
  copyright,
} = JSON.parse(readFileSync(arg('in', source), 'utf8'));
const target = arg('out', out);

/**
 * A short key with no whitespace, quote, backslash, or control character, so
 * it is a valid C++ string literal. Non-ASCII keys are kept: `文言` is a real
 * fence language, and dropping it would make a file name fall back to `txt`.
 *
 * ASCII case is required to be absent, because `extensionForLanguage` folds the
 * fence's language to lower case before it binary-searches this table, and that
 * search is only correct while every key is already folded.
 */
function isKey(key) {
  return (
    Buffer.byteLength(key, 'utf8') <= 32 &&
    !/[\s"\\\x00-\x1f\x7f]/.test(key) &&
    !/[A-Z]/.test(key)
  );
}

function isExtension(value) {
  return /^[A-Za-z0-9_.-]{1,16}$/.test(value);
}

const skipped = Object.entries(map)
  .filter(([key, value]) => !isKey(key) || !isExtension(value))
  .map(([key]) => key);
if (skipped.length > 0) {
  console.error(
    `skipping ${skipped.length} unusable entries: ${skipped.join(', ')}`
  );
}

const entries = Object.entries(map)
  .filter(([key, value]) => isKey(key) && isExtension(value))
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const keys = new Set(entries.map(([key]) => key));
const duplicates = entries
  .map(([key]) => key)
  .filter((key, index, all) => all.indexOf(key) !== index);
if (duplicates.length > 0) {
  console.error(
    `refusing to write: duplicate keys ${[...new Set(duplicates)].join(', ')}`
  );
  process.exit(1);
}
if (keys.size === 0) {
  console.error('refusing to write: no usable entries');
  process.exit(1);
}

const cString = (text) => `"${text.replace(/[\\"]/g, '\\$&')}"`;

const body = `// Generated by generate-export-names.mjs. Do not edit.
//
// The fence-language to file extension table a code download names its file
// with, taken from Streamdown's \`languageExtensionMap\`:
//
//   ${origin}
//   at ${commit}, licensed under ${license}.
//
//   ${copyright}
//
// Licensed under the Apache License, Version 2.0 (the "License"); you may not
// use this file except in compliance with the License. You may obtain a copy
// of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS, WITHOUT
// WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied. See the
// License for the specific language governing permissions and limitations under
// the License.

#include "ExportNames.h"

#include <algorithm>
#include <array>
#include <cstring>
#include <string>

namespace downstream {
namespace {

struct Entry {
  const char *language;
  const char *extension;
};

// Sorted by language, lower-cased, and compared in place, so a lookup is one
// binary search over a static table rather than a hash built on first use. The
// keys are lower-cased because the lookup folds the fence's language the same
// way; the generator refuses an entry that is not.
constexpr Entry kExtensions[] = {
${entries.map(([key, value]) => `    {${cString(key)}, ${cString(value)}},`).join('\n')}
};

} // namespace

std::string_view extensionForLanguage(std::string_view language) {
  // A fence is written by hand, so \`TS\`, \`Ts\`, and \`ts\` all mean TypeScript and
  // all three are common. Folding ASCII case before the search is what keeps a
  // capitalised fence from falling back to \`txt\`; the table is already folded,
  // so the search stays correct.
  std::string folded;
  folded.reserve(language.size());
  for (const char unit : language) {
    folded.push_back(unit >= 'A' && unit <= 'Z' ? static_cast<char>(unit - 'A' + 'a') : unit);
  }
  const auto *found = std::lower_bound(
      std::begin(kExtensions), std::end(kExtensions), folded,
      [](const Entry &entry, const std::string &key) {
        return std::string_view(entry.language) < std::string_view(key);
      });
  if (found == std::end(kExtensions) || std::string_view(found->language) != folded) {
    return {};
  }
  return found->extension;
}

} // namespace downstream
`;

writeFileSync(target, body);
console.error(`wrote ${entries.length} entries to ${target}`);

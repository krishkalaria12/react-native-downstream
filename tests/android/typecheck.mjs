// Type-checks the Android source set without Gradle.
//
//     node tests/android/typecheck.mjs
//
// `pnpm test:native` compiles the engine for the host and `pnpm test:kotlin` runs
// the mirrors' tables, but neither looks at `src/android/src/main/java` or the JNI
// sources: a change there passes both and still fails the first Gradle build on a
// device. This closes that gap with what the machine already has.
//
// It assembles a classpath out of what is already on disk:
//
//   - the Android platform's `android.jar`, for the framework types
//   - the cached `react-android` AAR's `classes.jar` and its prefab headers, which
//     is React Native exactly as Gradle would resolve it
//   - the cached Fresco, AndroidX, fbjni and soloader artifacts, which is the rest
//     of what the library compiles against
//   - React Native's *real* codegen output, generated by running its own codegen
//     over this package's spec, so the view manager interface is the generated one
//     rather than a hand-written approximation of it
//   - four stubs for classes that only a real Gradle build produces: the library's
//     own `R` and React Native's, and two annotations their generated code uses
//
// What it deliberately does not do is link or run anything. It proves the sources
// type-check against the versions this app will actually resolve, which is the part
// that catches a stale signature or a moved API; behaviour is the mirror tables'
// job and an instrumentation test's.
//
// Needs the Android SDK (`ANDROID_HOME`, or `~/Library/Android/sdk`), an NDK for
// the JNI check, a Kotlin compiler, and a populated Gradle cache. Every one of those
// is a "run it once in a real Android build" prerequisite, so a miss is a skipped
// check with a message rather than a failure.
import { execFileSync, spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const kotlinSources = join(repo, 'src', 'android', 'src', 'main', 'java', 'com', 'downstream');
const jniSources = join(repo, 'src', 'android', 'src', 'main', 'jni');
const cache = join(process.env.HOME ?? '', '.gradle', 'caches', 'modules-2', 'files-2.1');

/** Says why a check is not running and returns null, so a miss is not a failure. */
function skip(reason) {
  console.log(`SKIP android typecheck: ${reason}`);
  return null;
}

function findRuntimes() {
  const sdk = process.env.ANDROID_HOME ?? join(process.env.HOME ?? '', 'Library', 'Android', 'sdk');
  if (!existsSync(sdk)) {
    return skip(`no Android SDK at ${sdk}`);
  }
  const platforms = join(sdk, 'platforms');
  const platform = existsSync(platforms)
    ? readdirSync(platforms)
        .map((name) => join(platforms, name, 'android.jar'))
        .filter(existsSync)
        .sort()
        .pop()
    : undefined;
  if (!platform) {
    return skip('no android.jar in the SDK');
  }
  const ndkRoot = join(sdk, 'ndk');
  const ndk = existsSync(ndkRoot) ? readdirSync(ndkRoot).sort().reverse().find((n) => existsSync(join(ndkRoot, n))) : undefined;
  const clang = ndk
    ? join(ndkRoot, ndk, 'toolchains', 'llvm', 'prebuilt', 'darwin-x86_64', 'bin', 'clang++')
    : undefined;
  if (!clang || !existsSync(clang)) {
    return skip('no NDK clang++');
  }
  const java = spawnSync('java', ['-version'], { stdio: 'ignore' }).status === 0;
  if (!java || spawnSync('kotlinc', ['-version'], { stdio: 'ignore' }).status !== 0) {
    return skip('no java or kotlinc');
  }
  return { sdk, platform, clang };
}

/** The `react-android` AAR the package's own devDependency version resolves to. */
function reactAndroidAar() {
  const group = join(cache, 'com.facebook.react', 'react-android');
  if (!existsSync(group)) {
    return skip('react-android is not in the Gradle cache');
  }
  const wanted = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8')).devDependencies?.['react-native'];
  const versions = readdirSync(group)
    .filter((name) => existsSync(join(group, name)))
    // The version the package asks for, newest first otherwise: a mismatch is
    // still worth checking against, and the error it produces is a real one.
    .sort((a, b) => (a === wanted ? -1 : b === wanted ? 1 : b.localeCompare(a)));
  for (const version of versions) {
    const builds = join(group, version);
    for (const hash of readdirSync(builds)) {
      for (const file of readdirSync(join(builds, hash))) {
        if (file.endsWith('-debug.aar')) {
          return join(builds, hash, file);
        }
      }
    }
  }
  return skip('no react-android AAR in the Gradle cache');
}

/** Unpacks one AAR's classes.jar into the output directory, named after it. */
function classesOf(aar, out) {
  // Checked before extracting because an AAR need not carry one: a Kotlin Multiplatform
  // artifact ships its classes in a sibling `-jvm` jar instead, and `unzip` exits
  // non-zero when asked for a member that is not there.
  const listing = (spawnSync('unzip', ['-l', aar], { encoding: 'utf8' }).stdout ?? '').split('\n');
  if (!listing.some((line) => line.trimEnd().endsWith('classes.jar'))) {
    return null;
  }
  const scratch = mkdtempSync(join(tmpdir(), 'downstream-aar-'));
  try {
    execFileSync('unzip', ['-o', '-q', aar, 'classes.jar', '-d', scratch], { stdio: 'ignore' });
    const jar = join(scratch, 'classes.jar');
    if (!existsSync(jar)) {
      return null;
    }
    const target = join(out, `${aar.split('/').pop().replace('.aar', '')}.jar`);
    cpSync(jar, target);
    return target;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

/**
 * Every cached artifact whose group id starts with one of `groups`.
 *
 * The group id is one path segment with its dots in it, the way Maven and Gradle
 * lay out `files-2.1`, so `androidx.lifecycle` is a directory rather than
 * `androidx/lifecycle`. Splitting it on the dot is the mistake that makes a group
 * look absent when it is cached.
 *
 * A prefix rather than an exact match, because `androidx` alone is one group and
 * `androidx.annotation` is another, and the source set needs both: the generated
 * view manager imports `androidx.annotation.Nullable`, which lives in a group that
 * an exact `androidx` lookup never finds.
 */
function artifacts(groups) {
  const found = [];
  const roots = readdirSync(cache)
    .filter((name) => groups.some((group) => name === group || name.startsWith(`${group}.`)))
    .map((name) => join(cache, name));
  for (const root of roots) {
    for (const module of readdirSync(root)) {
      const versions = join(root, module);
      if (!existsSync(versions)) continue;
      for (const version of readdirSync(versions).sort().reverse()) {
        for (const hash of readdirSync(join(versions, version))) {
          const dir = join(versions, version, hash);
          if (!existsSync(dir)) continue;
          for (const file of readdirSync(dir)) {
            if ((file.endsWith('.jar') || file.endsWith('.aar')) && !file.includes('sources')) {
              found.push(join(dir, file));
            }
          }
        }
      }
    }
  }
  return found;
}

function run(label, command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8' });
  if (result.status !== 0) {
    console.log(`FAIL ${label}`);
    // The compiler's own output, not a summary: a type error's text is the only
    // thing that says what to fix.
    process.stdout.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    return false;
  }
  console.log(`ok ${label}`);
  return true;
}

const toolchain = findRuntimes();
const aar = toolchain && reactAndroidAar();
if (!toolchain || !aar) {
  process.exit(0);
}

const work = mkdtempSync(join(tmpdir(), 'downstream-android-'));
try {
  const jars = join(work, 'jars');
  const unpacked = join(work, 'aar');
  const classes = join(work, 'classes');
  const generated = join(work, 'generated');
  mkdirSync(jars, { recursive: true });
  mkdirSync(unpacked, { recursive: true });
  mkdirSync(classes, { recursive: true });
  mkdirSync(generated, { recursive: true });

  execFileSync('unzip', ['-o', '-q', aar, '-d', unpacked], { stdio: 'ignore' });
  const reactJar = join(unpacked, 'classes.jar');
  if (!existsSync(reactJar)) {
    skip('react-android AAR has no classes.jar');
    process.exit(0);
  }
  const classpath = [reactJar, toolchain.platform];

  // The rest of what the library compiles against, as Gradle would resolve it.
  const others = artifacts(['com.facebook.fresco', 'com.facebook.fbjni', 'com.facebook.soloader', 'androidx']);
  for (const other of others) {
    if (other.endsWith('.jar')) {
      classpath.push(other);
    } else {
      const extracted = classesOf(other, jars);
      if (extracted) {
        classpath.push(extracted);
      }
    }
  }

  // Four stubs for what only a real resource merge produces. Each one names what it
  // stands in for, so a reader knows these are harness scaffolding and not code.
  const stubSources = {
    'com/downstream/R.java': `package com.downstream;
/** Stub for the R class AAPT generates from this library's resources. */
public final class R {
  public static final class drawable {
    public static final int ds_ic_check = 1, ds_ic_collapse = 2, ds_ic_copy = 3;
    public static final int ds_ic_download = 4, ds_ic_expand = 5, ds_ic_wrap = 6;
  }
  public static final class id { public static final int copy = 1, cut = 2; }
  public static final class string { public static final int link_description = 1; }
}`,
    'com/facebook/react/R.java': `package com.facebook.react;
/** Stub for the R class React Native's own build generates from its resources. */
public final class R {
  public static final class string { public static final int link_description = 1, unspecified = 2; }
}`,
    'com/facebook/proguard/annotations/DoNotStrip.java': `package com.facebook.proguard.annotations;
import java.lang.annotation.*;
/** Stub: the real annotation ships in an AAR outside this classpath. */
@Retention(RetentionPolicy.CLASS) public @interface DoNotStrip {}`,
    'javax/annotation/Nonnull.java': `package javax.annotation;
import java.lang.annotation.*;
/** Stub: JSR-305, which the generated spec references. */
@Retention(RetentionPolicy.RUNTIME) public @interface Nonnull {}`,
    'javax/annotation/Nullable.java': `package javax.annotation;
import java.lang.annotation.*;
/** Stub: JSR-305, which the generated spec references. */
@Retention(RetentionPolicy.RUNTIME) public @interface Nullable {}`,
  };
  for (const [path, body] of Object.entries(stubSources)) {
    const target = join(generated, 'stubs', path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, body);
  }
  const stubSourcesList = Object.keys(stubSources).map((path) => join(generated, 'stubs', path));
  if (!run('java stubs', 'javac', ['-nowarn', '-proc:none', '-d', classes, ...stubSourcesList])) {
    process.exit(1);
  }
  classpath.push(classes);

  // React Native's own codegen, over this package's own spec. The generated view
  // manager interface is the one that ships, so a prop the manager forgot to
  // implement fails here rather than at the first Gradle build.
  const codegenOk = run(
    'codegen',
    'node',
    [
      join(repo, 'node_modules', 'react-native', 'scripts', 'generate-codegen-artifacts.js'),
      '--path',
      repo,
      '--outputPath',
      join(work, 'codegen'),
      '--targetPlatform',
      'android',
    ],
  );
  if (!codegenOk) {
    process.exit(1);
  }
  const generatedJava = join(work, 'codegen', 'android', 'app', 'build', 'generated', 'source', 'codegen', 'java');
  if (!existsSync(generatedJava)) {
    skip('codegen produced no Android java');
    process.exit(0);
  }
  const javaList = listFiles(generatedJava, '.java');
  if (!run('generated java', 'javac', ['-nowarn', '-proc:none', '-classpath', classpath.join(':'), '-d', classes, ...javaList])) {
    process.exit(1);
  }

  const ok = run(
    'kotlin source set',
    'kotlinc',
    [
      '-nowarn',
      '-jvm-target',
      '17',
      '-classpath',
      classpath.join(':'),
      '-d',
      join(work, 'out'),
      ...listFiles(kotlinSources, '.kt'),
    ],
  );

  // The JNI sources, against React Native's prefab headers and the NDK. This is the
  // half that catches a stale signature in `measurePlatform`, which no Kotlin check
  // would see.
  const prefab = join(unpacked, 'prefab', 'modules');
  const fbjniAar = artifacts(['com.facebook.fbjni']).find((file) => file.endsWith('.aar'));
  const fbjniUnpacked = join(work, 'fbjni');
  mkdirSync(fbjniUnpacked, { recursive: true });
  if (fbjniAar) {
    execFileSync('unzip', ['-o', '-q', fbjniAar, '-d', fbjniUnpacked], { stdio: 'ignore' });
  }
  const cpp = join(repo, 'src', 'cpp');
  const includes = [
    join(prefab, 'reactnative', 'include'),
    join(prefab, 'jsi', 'include'),
    join(fbjniUnpacked, 'prefab', 'modules', 'fbjni', 'include'),
    join(fbjniUnpacked, 'prefab', 'modules', 'lyra', 'include'),
    cpp,
    join(cpp, 'downstream'),
    join(cpp, 'session'),
    join(cpp, 'fabric'),
    join(cpp, 'remend'),
    join(cpp, 'highlight'),
    join(cpp, 'theme'),
    join(cpp, 'math'),
    join(cpp, 'md4c'),
    join(cpp, 'lexilla'),
    join(cpp, 'lexilla', 'lexlib'),
    jniSources,
  ]
    .filter(existsSync)
    .map((path) => `-I${path}`);
  // FOLLY_NO_CONFIG skips the generated `folly-config.h`, which a prefab consumer
  // is expected to supply; nothing here reads anything it would define.
  const defines = [
    '-DFOLLY_NO_CONFIG=1',
    '-DMD4C_USE_UTF8=1',
    '-Dmd_parse=downstream_md_parse',
    '-Dentity_lookup=downstream_entity_lookup',
    '-DLexilla=downstream_lexilla',
    '-DScintilla=downstream_scintilla',
    '-std=c++20',
  ];
  // Every directory under `src/cpp` has to be one both native builds compile and
  // can find headers in. A directory added to the engine and left out of the build
  // files does not fail any configure step: the library links and then fails on the
  // first undefined symbol, which reads like a platform problem rather than a
  // missing source. Comparing the two lists is what makes that a one-line failure
  // here instead.
  //
  // `lexilla`, `md4c` and `tests` are excluded: the first two are vendored and built
  // by their own rules, and the third is not shipped at all.
  const cmake = readFileSync(join(jniSources, 'CMakeLists.txt'), 'utf8');
  const podspec = readFileSync(join(repo, 'Downstream.podspec'), 'utf8');
  // The literal text CMake uses, written with concatenation so a template literal
  // does not try to interpolate it.
  const cmakeDir = '$' + '{LIB_CPP_DIR}';
  const excluded = ['lexilla', 'md4c', 'tests'];
  const engineDirs = readdirSync(cpp, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !excluded.includes(entry.name))
    .map((entry) => entry.name);
  const missing = [];
  for (const dir of engineDirs) {
    if (!cmake.includes(cmakeDir + '/' + dir + '/*.cpp')) {
      missing.push('CMakeLists.txt does not compile src/cpp/' + dir);
    }
    if (!podspec.includes('src/cpp/' + dir + '/*')) {
      missing.push('Downstream.podspec does not ship src/cpp/' + dir);
    }
    // A header spelled without its directory, the way
    // `downstream/PreparedDocument.cpp` includes `MathBlocks.h`, needs that
    // directory on the search path rather than only its parent.
    if (!cmake.includes(cmakeDir + '/' + dir + '\n') && !cmake.includes(cmakeDir + '/' + dir + ' ')) {
      missing.push('CMakeLists.txt does not put src/cpp/' + dir + ' on the include path');
    }
    if (!podspec.includes('src/cpp/' + dir + '\\"')) {
      missing.push('Downstream.podspec does not put src/cpp/' + dir + ' on the include path');
    }
  }
  if (missing.length > 0) {
    console.log('FAIL engine directories are not all built');
    for (const line of missing) {
      console.log('  ' + line);
    }
    process.exit(1);
  }
  console.log('ok engine directories (' + engineDirs.length + ') are built on both platforms');

  for (const source of listFiles(jniSources, '.cpp')) {
    if (
      !run(
        `jni ${source.split('/').pop()}`,
        toolchain.clang,
        ['--target=aarch64-linux-android24', '-fsyntax-only', ...defines, ...includes, source],
      )
    ) {
      process.exit(1);
    }
  }

  process.exit(ok ? 0 : 1);
} finally {
  if (!process.env.DOWNSTREAM_KEEP) {
    rmSync(work, { recursive: true, force: true });
  } else {
    console.error('kept', work);
  }
}

function listFiles(root, extension) {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(path);
      } else if (path.endsWith(extension)) {
        found.push(path);
      }
    }
  };
  if (existsSync(root)) {
    walk(root);
  }
  return found;
}
/**
 * Broken-markdown inputs ported from the remend test suite.
 *
 * remend is Vercel's streaming markdown repair pass (Apache-2.0), the one part
 * of Streamdown that runs ahead of the parser. Its own tests assert on the
 * repaired string, so they could not be reused directly. The inputs are what
 * matter: hundreds of shapes of markdown a model can emit mid-token, and that a
 * renderer must survive without inventing syntax.
 *
 * Every input here is a stream-boundary case. Nothing in this file is a
 * preference about how incomplete markdown should look, so the assertions in
 * `streaming-preview.test.ts` are invariants rather than expected output. The
 * cases that do carry a documented answer are written out in that file.
 *
 * How these were collected: every string literal in remend's `__tests__`, minus
 * the `it`/`describe` description arguments, minus the single-word probes that
 * exercise remend's own handler API rather than markdown. That is a deliberate
 * superset, and a checked one: a separate walk that resolves every call site
 * finds nothing here that is missing from this list, apart from those probes and
 * one string it misreads.
 *
 * The superset is the point. A call-site walk misses the literals that reach
 * remend through a `const`, through an `it.each` table, through
 * `array.join`, and through a destructured object property, and it is easy to
 * write one that looks complete. It also picks up the expected values, which
 * are themselves markdown a reader can send. A few of those carry remend's
 * `streamdown:incomplete-*` sentinel, which is a string a parser still has to
 * survive.
 *
 * The seed generator, the long-input case, and the composed multi-line
 * documents cannot live in a source file, so `streaming-preview.test.ts` builds
 * them instead.
 *
 * Provenance: github.com/vercel/streamdown, packages/remend/__tests__. The
 * inputs are markdown syntax, which is not copyrightable, and are reproduced
 * here under Apache-2.0 with this notice.
 */

